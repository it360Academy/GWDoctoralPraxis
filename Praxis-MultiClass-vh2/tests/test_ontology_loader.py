from pathlib import Path

from src.ontology.excludes1_loader import (Excludes1Pair, load_pairs_csv,
                                            write_pairs_csv)


def test_write_then_load_pairs_csv_roundtrips(tmp_path: Path):
    pairs = [
        Excludes1Pair(
            fiscal_year="TEST", home_code="A41", home_desc="Other sepsis",
            home_level="category", target_raw="P368", target_kind="prefix",
            target_lo="P368", target_hi="P368", note_text="test",
            direction="phenotype_is_home", phenotype="sepsis",
            source_chapter="1", source_section="A00-A49",
        ),
    ]
    out = tmp_path / "pairs.csv"
    write_pairs_csv(pairs, out)
    assert out.exists()

    loaded = load_pairs_csv(out)
    assert len(loaded) == 1
    assert loaded[0].home_code == "A41"
    assert loaded[0].phenotype == "sepsis"
    assert loaded[0].target_raw == "P368"


def test_seed_ontology_file_loads_if_present():
    """Regression guard: the smoke-test SEED ontology (generated by
    scripts/generate_synthetic_data.py) must always be loadable by the
    same code path main.py uses."""
    root = Path(__file__).resolve().parents[1]
    seed_path = root / "ontology" / "excludes1_pairs_vSEED.csv"
    if not seed_path.exists():
        return  # not generated yet in this environment; ingest/smoke tests cover this
    pairs = load_pairs_csv(seed_path)
    assert len(pairs) > 0
    assert all(p.phenotype == "sepsis" for p in pairs)
